#!/usr/bin/env python3
"""Generate an 8x16 bitmap font (Latin + Cyrillic) for the ESP32-S3 firmware.

The firmware draws text straight into an RGB565 framebuffer, so it needs a
plain 1-bit-per-pixel font with a fixed 8x16 cell. DejaVu Sans Mono is a good
source: its Cyrillic coverage is complete and it stays readable at 14 px.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CELL_W, CELL_H = 8, 16
FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
FONT_SIZE = 14
OUT = Path(__file__).resolve().parent.parent / "components" / "jc3248_media" / "font_8x16.h"

codepoints = list(range(0x20, 0x7F))
codepoints += [
    0x00B0, 0x00AB, 0x00BB, 0x2013, 0x2014, 0x2026,
    0x0401, 0x0404, 0x0406, 0x0407, 0x040E,
    0x0451, 0x0454, 0x0456, 0x0457, 0x045E,
]
codepoints += list(range(0x0410, 0x0450))
codepoints = sorted(set(codepoints))

font = ImageFont.truetype(FONT_PATH, FONT_SIZE)
ascent, descent = font.getmetrics()
# Centre the glyph cell vertically; DejaVu's ascent at 14 px is 13.
y_off = (CELL_H - (ascent + descent)) // 2

glyphs = []
for cp in codepoints:
    img = Image.new("1", (CELL_W, CELL_H), 0)
    draw = ImageDraw.Draw(img)
    draw.text((0, y_off), chr(cp), font=font, fill=1)
    data = []
    for y in range(CELL_H):
        byte = 0
        for x in range(CELL_W):
            if img.getpixel((x, y)):
                byte |= 1 << x
        data.append(byte)
    glyphs.append(data)

lines = []
lines.append("// Generated by tools/make_font.py - do not edit by hand.")
lines.append("#pragma once")
lines.append("#include <stdint.h>")
lines.append("")
lines.append(f"#define FONT_CELL_W {CELL_W}")
lines.append(f"#define FONT_CELL_H {CELL_H}")
lines.append(f"#define FONT_GLYPH_COUNT {len(codepoints)}")
lines.append("")
lines.append("static const uint32_t font_codepoints[FONT_GLYPH_COUNT] = {")
for i in range(0, len(codepoints), 8):
    chunk = ", ".join(f"0x{cp:04X}" for cp in codepoints[i:i + 8])
    lines.append(f"    {chunk},")
lines.append("};")
lines.append("")
lines.append("static const uint8_t font_glyphs[FONT_GLYPH_COUNT][FONT_CELL_H] = {")
for cp, data in zip(codepoints, glyphs):
    rows = ", ".join(f"0x{b:02X}" for b in data)
    # Codepoint only: keep the generated comments ASCII-safe.
    lines.append(f"    {{{rows}}},  // U+{cp:04X}")
lines.append("};")
lines.append("")

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT} ({len(codepoints)} glyphs)")

# A quick visual check for a few glyphs, printed as ASCII art.
for ch in ("A", "a", chr(0x0416), chr(0x0449), "?"):
    idx = codepoints.index(ord(ch))
    print(f"--- {ch} ---")
    for row in glyphs[idx]:
        print("".join("#" if row & (1 << x) else "." for x in range(CELL_W)))
